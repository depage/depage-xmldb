namespace Depage\XmlDb\Helpers;

use Depage\XmlDb\Exceptions\XmlDbException;
use Depage\XmlDb\XmlNs;

/**
 * @internal canonical content and hashing of nodes; not part of the
 * public api of this library
 *
 * The (type, name, value) tupel these functions calculate from a DOM
 * node is exactly what DocumentWriter::saveNodeToDb stores in the
 * database, and the hash over that tupel plus the hashes of the children
 * is what is stored in the subhash column; saving and patching rely on
 * them producing identical results.
 *
 * Values are normalized (NFC) by the callers before they are stored or
 * hashed, so stored values and recalculated hashes always use the same
 * canonical form.
 */
class NodeContent
{
    // {{{ dbIdOf
    /**
     * reads the database id out of the db:id attribute of a node ('' if
     * the node does not carry one)
     */
    public static function dbIdOf($node, XmlNs $dbNs, string $idAttribute)
    {
        return $node->nodeType == XML_ELEMENT_NODE
            ? $node->getAttributeNS($dbNs->uri, $idAttribute)
            : null;
    }
    // }}}
    // {{{ fromDomNode
    /**
     * returns the (type, name, value) tupel a DOM node is saved as, in
     * exactly the same way saveNodeToDb stores it; needed to calculate
     * the hashes of nodes that are not in the database (yet)
     */
    public static function fromDomNode($node, XmlNs $dbNs, string $idAttribute): array
    {
        if ($node->nodeType == XML_ELEMENT_NODE) {
            if ($node->prefix != '') {
                $nodeName = $node->prefix . ':' . $node->localName;
            } else {
                $nodeName = $node->localName;
            }

            $attributes = [];
            foreach ($node->attributes as $attrib) {
                $attribNs = ($attrib->prefix == '') ? '' : $attrib->prefix . ':';

                $attributes[$attribNs . $attrib->localName] = $attrib->value;
            }

            return ['ELEMENT_NODE', $nodeName, self::attributeString($attributes, $dbNs, $idAttribute)];
        } elseif ($node->nodeType == XML_TEXT_NODE) {
            return ['TEXT_NODE', null, $node->textContent];
        } elseif ($node->nodeType == XML_COMMENT_NODE) {
            return ['COMMENT_NODE', null, $node->textContent];
        } elseif ($node->nodeType == XML_PI_NODE) {
            return ['PI_NODE', $node->target, $node->textContent];
        } elseif ($node->nodeType == XML_ENTITY_REF_NODE) {
            return ['ENTITY_REF_NODE', null, $node->nodeName];
        }

        throw new XmlDbException('Unknown DOM node type: "' . $node->nodeType . '".');
    }
    // }}}
    // {{{ attributeString
    /**
     * builds the attribute string a node's value column holds from the
     * attributes of a node, sorted by name, without the attributes that
     * the database generates itself (db:id and the change markers)
     *
     * @param $attributes (array) array of attribute values
     */
    public static function attributeString(array $attributes, XmlNs $dbNs, string $idAttribute): string
    {
        $attrStr = '';
        $autogeneratedAttr = [
            $dbNs->ns . ':' . $idAttribute,
            $dbNs->ns . ':released',
            $dbNs->ns . ':lastchange',
            $dbNs->ns . ':lastchangeUid',
        ];
        ksort($attributes);
        foreach ($attributes as $name => $value) {
            if (!in_array($name, $autogeneratedAttr)) {
                $attrStr .= "$name=\"" . htmlspecialchars($value) . "\" ";
            }
        }

        return $attrStr;
    }
    // }}}
    // {{{ hash
    /**
     * canonical hash over one node row and the hashes of its children;
     * the "v1" prefix pins the canonicalization, changing the format
     * invalidates all stored hashes on the next recalculation
     *
     * @param $type (string) node type as stored in the database
     * @param $name (string) node name as stored in the database
     * @param $value (string) node value as stored in the database
     * @param $childHashes (array) hashes of the children in document order
     */
    public static function hash($type, $name, $value, array $childHashes): string
    {
        return hash('sha256', 'v1|' . $type . '|' . $name . '|' . $value . '|' . implode('|', $childHashes));
    }
    // }}}
}

